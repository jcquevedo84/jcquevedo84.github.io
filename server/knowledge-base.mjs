function normalize(value) {
  return value
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "");
}

export function selectKnowledge(messages, maximumTopics = 5) {
  const recentUserText = messages
    .filter((message) => message.role === "user")
    .slice(-3)
    .map((message) => message.content)
    .join(" ");
  const normalized = normalize(recentUserText);

  const rankedTopics = Object.entries(TOPIC_KEYWORDS)
    .map(([topic, keywords]) => ({
      topic,
      score: keywords.reduce((score, keyword) => score + (normalized.includes(normalize(keyword)) ? 1 : 0), 0),
    }))
    .filter(({ score }) => score > 0)
    .sort((left, right) => right.score - left.score)
    .slice(0, maximumTopics)
    .map(({ topic }) => topic);

  if (rankedTopics.length === 0) rankedTopics.push("career");

  const selectedTopics = ["summary", ...rankedTopics, "publicBoundaries"];
  return selectedTopics.map((topic) => ({ topic, content: PROFESSIONAL_KNOWLEDGE[topic].trim() }));
}
